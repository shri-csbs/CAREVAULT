/**
 * Formats a patient display name according to the rule:
 * If a name contains only a first/given name without a surname, append "Kumar".
 * Preserve names that already have a surname (e.g. "Aarav Kumar", "Vikram Reddy").
 * Do not duplicate "Kumar".
 */
export function formatPatientDisplayName(name: string): string {
  if (!name) return '';
  const trimmed = name.trim();
  const parts = trimmed.split(/\s+/).filter(Boolean);
  if (parts.length === 1) {
    return `${trimmed} Kumar`;
  }
  return trimmed;
}

